export function platformColor(key: string): string {
  return PLATFORM_COLORS[key as PlatformKey] ?? "#e8833a";
}

/** Renders a platform's logo in its brand colour (or an override). */
export function BrandIcon({
  platform,
  className,
  color,
}: {
  platform: string;
  className?: string;
  color?: string;
}) {
  return (
    <span className={className} style={{ color: color ?? platformColor(platform) }}>
      {getPlatform(platform).icon}
    </span>
  );
}

export function getPlatform(key: string): Platform {
  return PLATFORMS[key as PlatformKey] ?? PLATFORMS.other;
}

/** Only http(s), mailto and tel are ever emitted as an href. */
export function socialHref(platform: string, value: string): string | null {
  const built = getPlatform(platform).href(value.trim());
  if (/^(https?:|mailto:|tel:)/i.test(built)) return built;
  return null;
}
